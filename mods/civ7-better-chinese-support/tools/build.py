"""Rebuild only explicitly reviewed gameplay-description corrections.

Reads installed text assets offline. Never connects to or modifies the game.
"""
import argparse
import collections
import csv
import hashlib
import io
import os
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_GAME = Path(os.environ.get("CIV7_GAME_DIR", str(Path.home() / "Library/Application Support/Steam/steamapps/common/Sid Meier's Civilization VII/CivilizationVII.app/Contents/Resources")))
SOURCE = ROOT / "reference/upstream-2026-10-28.csv"
PRIORITY = {"勘误": 1, "替换音译": 2, "润色": 3}
SELECTION = ROOT / "reference/functional-selection.json"


def read_source_rules():
    rules = []
    for number, row in enumerate(csv.reader(io.StringIO(SOURCE.read_text(encoding="utf-8"))), 1):
        if not row or row[0] not in {*PRIORITY, "翻译MOD"}:
            continue
        category, civ, kind, before, after, english, tag = row[:7]
        assert after and (before or tag), (number, row)
        rules.append(dict(row=number, category=category, civ=civ, kind=kind,
                          before=before, after=after, english=english, tag=tag))
    return rules


def read_rules():
    groups = json.loads(SELECTION.read_text())
    selected = {row: group for group in groups for row in group["rows"]}
    rules = []
    for rule in read_source_rules():
        if rule["row"] not in selected:
            continue
        assert rule["category"] == "勘误" and rule["tag"], rule
        rule["group"] = selected[rule["row"]]["id"]
        if rule["row"] in (179, 181):
            rule["before"], rule["after"] = "每有1特色", "每有1种不同的"
        if rule["row"] in (191, 192):
            rule["after"] = "必须放置在草原平地上。"
        if rule["row"] in (195, 196):
            rule["after"] = "且此定居点必须位于岛屿上"
        if rule["row"] in (247, 248, 249):
            rule["after"] = rule["before"].replace("[LI]", "[LI]与水岸相邻的", 1).replace("，以及与水岸相邻的", "及")
        if rule["row"] in (250, 252):
            rule["after"] = rule["after"].replace("时，[TIP:", "时，在建造它的[TIP:")
        if rule["row"] in (259, 260):
            rule["after"] = "己方" + rule["after"]
        if rule["row"] in (265, 266):
            rule["after"] = "6格内每有一个其他己方定居点"
        rules.append(rule)
    assert {r["row"] for r in rules} == set(selected)
    return rules


def read_texts(game):
    texts = collections.defaultdict(set)
    files = []
    for subtree in ("Base", "DLC"):
        for path in sorted((game / subtree).rglob("*zh_Hans_CN*.xml")):
            root = ET.parse(path).getroot()
            files.append(dict(path=str(path.relative_to(game)), sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
            for node in root.iter():
                if node.get("Language") == "zh_Hans_CN" and node.get("Tag"):
                    text = node.findtext("Text")
                    if text is not None:
                        texts[node.get("Tag")].add(text)
    assert texts, "No Simplified Chinese game text assets found"
    return texts, files


def transform(tag, original, rules):
    # Match against the original once. Higher-priority modules win overlapping
    # spans; never feed translated output into another substring replacement.
    candidates = []
    for rule in rules:
        if not rule["before"] or (rule["tag"] and rule["tag"] != tag):
            continue
        for match in re.finditer(re.escape(rule["before"]), original):
            candidates.append((match.start(), match.end(), rule))
    candidates.sort(key=lambda x: (-PRIORITY[x[2]["category"]], -(x[1]-x[0]), x[2]["row"]))
    accepted = []
    for start, end, rule in candidates:
        if not any(start < b and end > a for a, b, _ in accepted):
            accepted.append((start, end, rule))
    result = original
    for start, end, rule in sorted(accepted, reverse=True, key=lambda x: x[0]):
        result = result[:start] + rule["after"] + result[end:]
    return result, sorted({r["row"] for _, _, r in accepted})


def quote(value):
    return "'" + value.replace("'", "''") + "'"


def write_patches(path, patches):
    lines = ["-- Generated by tools/build.py; Chinese text only.",
             "-- Community revisions: 徂川 / 简中翻译修正和改进 (3524742152).",
             "-- Exact original-text guards preserve later official/third-party edits."]
    for tag, before, after in patches:
        lines.append("UPDATE LocalizedText SET Text=" + quote(after) + " WHERE Language='zh_Hans_CN' AND Tag=" + quote(tag) + " AND Text=" + quote(before) + ";")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def additions(texts=None):
    # Retain official wording, markup, sentence order and yield descriptions.
    # Append missing placement conditions; replace only the false requirement.
    if texts is None:
        texts, _ = read_texts(DEFAULT_GAME)
    suffixes = {
        "LOC_IMPROVEMENT_JINJA_DESCRIPTION": "海上神社只能放置在与平地相邻的海岸地块上。相邻丘陵和山脉不满足海上神社的条件。",
        "LOC_IMPROVEMENT_JINJA_SEA_DESCRIPTION": "只能放置在与平地相邻的海岸地块上。相邻丘陵和山脉不满足条件。",
        "LOC_IMPROVEMENT_JINJA_SEA_TOOLTIP": "只能放置在与平地相邻的海岸地块上。相邻丘陵和山脉不满足条件。",
    }
    result = {}
    for tag, suffix in suffixes.items():
        originals = {v.strip() for v in texts[tag]}
        assert len(originals) == 1, (tag, originals)
        result[tag] = originals.pop() + "[n]" + suffix
    before = "拥有古典时代[TIP:LOC_PEDIA_CONCEPTS_BUILDINGS_TOOLTIP]建筑[/TIP]和至少1[icon:YIELD_HAPPINESS]"
    after = "拥有古典时代[icon:YIELD_HAPPINESS]幸福值[TIP:LOC_PEDIA_CONCEPTS_BUILDINGS_TOOLTIP]建筑[/TIP]"
    note = "[n]幸福值建筑按游戏建筑分类判定，不以区块的幸福值总产出判定。加成按区块计算，不按建筑数量叠加。"
    for kind in ("DESCRIPTION", "TOOLTIP"):
        tag = "LOC_WONDER_MIREUKSA_" + kind
        originals = {v.strip() for v in texts[tag]}
        assert len(originals) == 1, (tag, originals)
        original = originals.pop()
        assert original.count(before) == 1, tag
        result[tag] = original.replace(before, after) + note
    return result


def build(game):
    texts, files = read_texts(game)
    rules = read_rules()
    matches = collections.defaultdict(set)
    patches = []
    for tag in sorted(texts):
        for original in sorted(texts[tag]):
            revised, rows = transform(tag, original, rules)
            for row in rows:
                matches[row].add(tag)
            if revised != original:
                patches.append((tag, original, revised))
    missing = [r["row"] for r in rules if not matches[r["row"]]]
    assert not missing, f"Reviewed corrections no longer match; re-review: {missing}"
    write_patches(ROOT / "text/functional.sql", patches)
    extra = []
    for tag, after in additions(texts).items():
        assert tag in texts, tag
        # The native localization importer trims outer whitespace. Match both
        # the XML spelling and its native normalized spelling, not arbitrary text.
        for before in sorted({v for original in texts[tag] for v in (original, original.strip())}):
            extra.append((tag, before, after))
    write_patches(ROOT / "text/mechanics.sql", extra)
    selected = {r["row"] for r in rules}
    report = dict(scope="gameplay-description-corrections-only", version="0.2.1",
                  source_url="https://docs.qq.com/sheet/DWW94VHpnUFdHVmZS?tab=1nqnrb",
                  source_sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                  reviewed_rules=len(rules), functional_tags=len({p[0] for p in patches}),
                  own_tags=len(additions(texts)), game_text_files=files,
                  rows=[dict(**r, matched_tags=sorted(matches[r["row"]])) for r in rules],
                  excluded_rows=[dict(row=r["row"], category=r["category"], kind=r["kind"],
                                      reason="not-in-reviewed-functional-allowlist")
                                 for r in read_source_rules() if r["row"] not in selected])
    (ROOT / "docs/import-audit.json").write_text(json.dumps(report, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print(json.dumps({k:v for k,v in report.items() if k not in ("rows", "game_text_files", "excluded_rows")},ensure_ascii=False))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--game", type=Path, default=DEFAULT_GAME)
    build(parser.parse_args().game)
